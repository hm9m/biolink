export const BadgeGlyph: React.FC<{
  iconKey: BadgeIconKey;
  color: string;
  size?: number;
}> = ({ iconKey, color, size = 15 }) => {
  const props = { size, style: { color }, strokeWidth: 2.1 };
  switch (iconKey) {
    case 'crown':
      return <Crown {...props} />;
    case 'shield':
      return <Shield {...props} />;
    case 'star':
      return <Star {...props} />;
    case 'gem':
      return <Gem {...props} />;
    case 'heart':
      return <Heart {...props} />;
    case 'bug':
      return <Bug {...props} />;
    case 'bolt':
      return <Zap {...props} />;
    case 'award':
    default:
      return <Award {...props} />;
  }
};

export const ResilientImage: React.FC<{
  src: string;
  alt: string;
  className?: string;
  fallbackLabel?: string;
}> = ({ src, alt, className = '', fallbackLabel }) => {
  const [errored, setErrored] = useState(false);

  if (!src || errored) {
    return (
      <div
        className={`flex items-center justify-center bg-gradient-to-br from-[#16181F] to-[#0C0D12] text-zinc-400 select-none ${className}`}
        aria-label={alt}
      >
        <span className="font-display text-sm font-semibold tracking-tight uppercase">
          {(fallbackLabel || alt || 'C').slice(0, 2)}
        </span>
      </div>
    );
  }

  return (
    <img
      src={src}
      alt={alt}
      referrerPolicy="no-referrer"
      onError={() => setErrored(true)}
      className={className}
    />
  );
};

